#!/usr/bin/env python3
"""
Regenerates the "Appendix A" section of README.md from
docs/evidence/adversarial_results.json (the last LIVE run of
tests/run_adversarial_suite.py), so the prompt list and outcomes in the
README are copied from the evidence, never typed by hand.

Usage (from any folder):  python tests/render_results_appendix.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
RESULTS = ROOT / "docs" / "evidence" / "adversarial_results.json"
START, END = "<!-- APPENDIX:START -->", "<!-- APPENDIX:END -->"
LONG = 300


def cell(text: str) -> str:
    return (text.replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")
            .replace("\u200b", "&lt;U+200B&gt;").replace("\u200d", "&lt;U+200D&gt;")
            .replace("\u2060", "&lt;U+2060&gt;"))


def prompt_cell(item_id: str, prompt: str, long_prompts: dict) -> str:
    if len(prompt) <= LONG:
        return cell(prompt)
    long_prompts[item_id] = prompt
    return f"{cell(prompt[:120])}... *({len(prompt)} chars, full text below)*"


def render() -> str:
    data = json.loads(RESULTS.read_text(encoding="utf-8"))
    s = data["summary"]
    lines = [
        START,
        f"Generated by `tests/render_results_appendix.py` from the live run of "
        f"{s['run_at']} (`docs/evidence/adversarial_results.json`, which also holds every full reply). "
        f"Invisible characters are shown as &lt;U+....&gt;. "
        f"**Expected**: refuse / answer / safe (refused, or answered without the smuggled part) / any. "
        f"**Actual**: the layer that stopped it, read from `audit.jsonl`.",
        "",
    ]
    long_prompts: dict[str, str] = {}
    singles = [r for r in data["results"] if r["kind"] == "single"]
    lines += ["### A.1 Single-turn prompts", "",
              "| id | category | prompt (verbatim) | expected | actual | ok |", "|---|---|---|---|---|---|"]
    for r in singles:
        lines.append(f"| {r['id']} | {r['category']} | {prompt_cell(r['id'], r['prompt'], long_prompts)} | "
                     f"{r['expected']} | {r['outcome']} | {'yes' if r['correct'] else '**NO**'} |")
    lines += ["", "### A.2 Multi-turn scenarios (fresh session per scenario)", "",
              "| turn | prompt (verbatim) | expected | actual | input / context score | ok |",
              "|---|---|---|---|---|---|"]
    for r in data["results"]:
        if r["kind"] != "multi_turn":
            continue
        scores = f"{r['input_score']} / {r['context_score']}" if r["input_score"] is not None else "--"
        lines.append(f"| {r['id']} | {prompt_cell(r['id'], r['prompt'], long_prompts)} | {r['expected']} | "
                     f"{r['outcome']} | {scores} | {'yes' if r['correct'] else '**NO**'} |")
    if long_prompts:
        lines += ["", "### A.3 Full text of long prompts", ""]
        for item_id, prompt in long_prompts.items():
            lines += [f"<details><summary>{item_id} ({len(prompt)} characters)</summary>", "",
                      "```text", prompt, "```", "", "</details>", ""]
    lines.append(END)
    return "\n".join(lines)


def main() -> None:
    readme = README.read_text(encoding="utf-8")
    if START not in readme or END not in readme:
        raise SystemExit(f"README.md needs {START} and {END} markers")
    before, rest = readme.split(START, 1)
    after = rest.split(END, 1)[1]
    README.write_text(before + render() + after, encoding="utf-8")
    print("README.md appendix regenerated")


if __name__ == "__main__":
    main()
